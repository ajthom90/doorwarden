// Package traefik renders doorwarden's persisted route set, middleware
// definitions and certificate list into Traefik v3 file-provider dynamic
// configuration, and writes it atomically into Traefik's watched directory.
//
// The package is pure apart from Write: it reads no store, no key material
// and no clock.
//
// # Rendering rules
//
//   - One router per hostname (compared case-insensitively). When several
//     rows share a hostname (a crash window, or a source outage; see
//     internal/reconcile doc.go) the winner is the row with the strongest
//     reconcile.SourceRank (static > truenas > docker > other), then the
//     smaller key: the same rule the reconcile tests' renderer-agreement
//     helper encodes. The other rows get a Problem of KindShadowed.
//   - The winner is chosen BEFORE it is validated. When the winner cannot be
//     rendered (invalid hostname or backend, malformed or undefined
//     middleware) the hostname is left dark: a shadowed, lower-ranked row is
//     never served in its place.
//   - Middlewares fail closed: a route whose middleware reference is not
//     defined (see model.CheckMiddlewareRef) gets no router and no service.
//     Traefik's handling of a router with a missing middleware differs
//     between versions; an auth-protected app must never be reachable
//     without its auth.
//   - Routes with RemovedAfter set are still rendered: they are live until
//     the reconciler's RouteRemove deletes the row.
//   - Certificates come from tls.certificates in TLSFile; routers carry an
//     empty "tls: {}" and never a certResolver (Traefik's ACME is not used).
package traefik

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"net"
	"path"
	"sort"
	"strconv"
	"strings"

	"github.com/ajthom90/doorwarden/internal/model"
	"github.com/ajthom90/doorwarden/internal/reconcile"
	"github.com/ajthom90/doorwarden/internal/store"
	"gopkg.in/yaml.v3"
)

// File names written into Traefik's dynamic configuration directory.
const (
	RoutesFile = "doorwarden-routes.yml"
	TLSFile    = "doorwarden-tls.yml"
)

// Header is the first line of every file doorwarden writes. Write only
// removes stale files that start with it (and carry the doorwarden- prefix).
const Header = "# doorwarden-managed: generated by doorwarden, do not edit\n"

// InsecureTransport is the shared serversTransport used by https backends
// with skip_verify.
const InsecureTransport = "doorwarden-insecure"

// Defaults for Options.
const (
	DefaultEntryPoint = "websecure"
	DefaultPathPrefix = "/certs"
)

// Problem kinds.
const (
	// KindShadowed: another row holds the same hostname with precedence.
	KindShadowed = "shadowed"
	// KindUndefinedMiddleware: the route references a middleware that is
	// neither (validly) defined nor allowlisted; the route is not rendered.
	KindUndefinedMiddleware = "undefined-middleware"
	// KindInvalidMiddleware: a middleware reference is malformed; the route
	// is not rendered.
	KindInvalidMiddleware = "invalid-middleware"
	// KindInvalidDefinition: a middleware definition is malformed and is not
	// rendered (routes referencing it are then undefined-middleware).
	KindInvalidDefinition = "invalid-middleware-definition"
	// KindInvalidRoute: the row's hostname or backend fails validation.
	KindInvalidRoute = "invalid-route"
	// KindInvalidCert: a TLSCert has an unsafe or malformed path.
	KindInvalidCert = "invalid-cert"
)

// Files maps a file name (no directory) to its content.
type Files map[string][]byte

// TLSCert is one certificate for tls.certificates. CertFile and KeyFile are
// slash-separated paths RELATIVE to Options.PathPrefix, i.e. as Traefik sees
// them below the certificate mount; no key material is read. An entry
// without Domains is not rendered.
type TLSCert struct {
	Domains           []string
	CertFile, KeyFile string
}

// MiddlewareDefs maps a middleware name (no "@provider") to its definition,
// a mapping of exactly one Traefik middleware type to its options. It is
// rendered verbatim under http.middlewares.
type MiddlewareDefs map[string]any

// Options tunes rendering. Traefik's own ACME (certResolver) is never used.
type Options struct {
	// EntryPoint for every router; default DefaultEntryPoint.
	EntryPoint string
	// PathPrefix is prepended to TLSCert paths; default DefaultPathPrefix.
	PathPrefix string
	// ExternalMiddlewares allowlists qualified references ("name@provider")
	// to middlewares defined outside doorwarden's definitions.
	ExternalMiddlewares []string
}

// Problem reports something not rendered.
type Problem struct {
	Kind string
	// Key and Hostname identify the route (empty for definition and cert
	// problems); Middleware names the reference or definition involved.
	Key, Hostname, Middleware string
	Detail                    string
}

func (p Problem) String() string {
	return fmt.Sprintf("%s %s %s %s: %s", p.Kind, p.Hostname, p.Key, p.Middleware, p.Detail)
}

// Name returns the Traefik object name (router and service) for a service
// key: a readable [a-z0-9-] slug of the key plus a short hash of the exact
// key, so distinct keys never share a name.
func Name(key string) string {
	var b strings.Builder
	dash := false
	for _, c := range []byte(strings.ToLower(key)) {
		if c >= 'a' && c <= 'z' || c >= '0' && c <= '9' {
			b.WriteByte(c)
			dash = false
		} else if !dash && b.Len() > 0 {
			b.WriteByte('-')
			dash = true
		}
	}
	slug := strings.TrimRight(b.String(), "-")
	if len(slug) > 40 {
		slug = strings.TrimRight(slug[:40], "-")
	}
	if slug == "" {
		slug = "svc"
	}
	sum := sha256.Sum256([]byte(key))
	return slug + "-" + hex.EncodeToString(sum[:])[:10]
}

// YAML document shapes. Field order is the output order.
type routesDoc struct {
	HTTP httpConf `yaml:"http"`
}

type httpConf struct {
	Routers           map[string]router    `yaml:"routers,omitempty"`
	Services          map[string]service   `yaml:"services,omitempty"`
	Middlewares       map[string]any       `yaml:"middlewares,omitempty"`
	ServersTransports map[string]transport `yaml:"serversTransports,omitempty"`
}

type router struct {
	EntryPoints []string `yaml:"entryPoints"`
	Rule        string   `yaml:"rule"`
	Service     string   `yaml:"service"`
	Middlewares []string `yaml:"middlewares,omitempty"`
	// TLS must render as "tls: {}" (never null): TLS on, certificate from
	// the file provider's tls.certificates.
	TLS struct{} `yaml:"tls"`
}

type service struct {
	LoadBalancer loadBalancer `yaml:"loadBalancer"`
}

// loadBalancer: websockets need no Traefik configuration (the proxy passes
// Upgrade requests through), so Route.Websockets renders nothing.
type loadBalancer struct {
	Servers          []server `yaml:"servers"`
	PassHostHeader   bool     `yaml:"passHostHeader"`
	ServersTransport string   `yaml:"serversTransport,omitempty"`
}

type server struct {
	URL string `yaml:"url"`
}

type transport struct {
	InsecureSkipVerify bool `yaml:"insecureSkipVerify"`
}

type tlsDoc struct {
	TLS tlsConf `yaml:"tls"`
}

// tlsConf holds tls.certificates only. Task 17 hook: the per-zone default
// certificate (tls.stores.default.defaultCertificate and SNI-default
// selection) is added here by Task 17; it is deliberately not rendered yet.
type tlsConf struct {
	Certificates []certEntry `yaml:"certificates,omitempty"`
}

type certEntry struct {
	CertFile string `yaml:"certFile"`
	KeyFile  string `yaml:"keyFile"`
}

func validEntryPoint(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_' || c == '-') {
			return false
		}
	}
	return true
}

// validRouteHostname: a DNS name accepted by model.ValidHost that is not an
// IP literal (its charset excludes backticks, so the Host() rule is safe).
func validRouteHostname(h string) bool {
	return h != "" && model.ValidHost(h) && net.ParseIP(h) == nil && !strings.HasPrefix(h, "[")
}

func pathChar(c byte) bool {
	return c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_' || c == '.' || c == '-' || c == '/'
}

func cleanPath(p string, abs bool) error {
	if p == "" {
		return errors.New("empty path")
	}
	for i := 0; i < len(p); i++ {
		if !pathChar(p[i]) {
			return fmt.Errorf("path %q has characters outside [A-Za-z0-9._/-]", p)
		}
	}
	if strings.HasPrefix(p, "/") != abs {
		if abs {
			return fmt.Errorf("path %q must be absolute", p)
		}
		return fmt.Errorf("path %q must be relative", p)
	}
	if path.Clean(p) != p {
		return fmt.Errorf("path %q is not clean", p)
	}
	for _, el := range strings.Split(p, "/") {
		if el == ".." || el == "." {
			return fmt.Errorf("path %q must not contain . or .. elements", p)
		}
	}
	return nil
}

// Render renders the route set, middleware definitions and certificates.
// It returns the content of RoutesFile and TLSFile, Problems for everything
// not rendered (sorted), and an error only for invalid Options or input that
// is a programming error (duplicate route keys, a name collision). Output is
// deterministic for any input order.
func Render(routes []store.Route, mw MiddlewareDefs, certs []TLSCert, opts Options) (Files, []Problem, error) {
	ep := opts.EntryPoint
	if ep == "" {
		ep = DefaultEntryPoint
	}
	if !validEntryPoint(ep) {
		return nil, nil, fmt.Errorf("traefik: entry point %q must be [A-Za-z0-9_-]+", ep)
	}
	prefix := opts.PathPrefix
	if prefix == "" {
		prefix = DefaultPathPrefix
	}
	if prefix != "/" {
		prefix = strings.TrimRight(prefix, "/")
	}
	if err := cleanPath(prefix, true); err != nil {
		return nil, nil, fmt.Errorf("traefik: path prefix: %w", err)
	}
	for _, e := range opts.ExternalMiddlewares {
		if err := model.ValidateExternalMiddleware(e); err != nil {
			return nil, nil, fmt.Errorf("traefik: external middleware: %w", err)
		}
	}

	var probs []Problem
	conf := httpConf{Routers: map[string]router{}, Services: map[string]service{},
		Middlewares: map[string]any{}, ServersTransports: map[string]transport{}}

	// Definitions: verbatim, only when valid.
	for name, def := range mw {
		if !model.ValidMiddlewareName(name) {
			probs = append(probs, Problem{Kind: KindInvalidDefinition, Middleware: name,
				Detail: "definition name must be [A-Za-z0-9_.-]+ (no @provider)"})
			continue
		}
		if err := model.ValidateMiddlewareDef(def); err != nil {
			probs = append(probs, Problem{Kind: KindInvalidDefinition, Middleware: name, Detail: err.Error()})
			continue
		}
		conf.Middlewares[name] = def
	}
	defined := func(n string) bool { _, ok := conf.Middlewares[n]; return ok }

	// Group rows by hostname.
	seenKey, seenName := map[string]bool{}, map[string]string{}
	byHost := map[string][]store.Route{}
	for _, r := range routes {
		if seenKey[r.Key] {
			return nil, nil, fmt.Errorf("traefik: duplicate route key %q", r.Key)
		}
		seenKey[r.Key] = true
		n := Name(r.Key)
		if o, dup := seenName[n]; dup {
			return nil, nil, fmt.Errorf("traefik: route keys %q and %q map to the same name %q", o, r.Key, n)
		}
		seenName[n] = r.Key
		h := strings.ToLower(r.Hostname)
		byHost[h] = append(byHost[h], r)
	}
	for h, group := range byHost {
		sort.Slice(group, func(i, j int) bool {
			ri := reconcile.SourceRank(group[i].Key, group[i].Source)
			rj := reconcile.SourceRank(group[j].Key, group[j].Source)
			if ri != rj {
				return ri < rj
			}
			return group[i].Key < group[j].Key
		})
		w := group[0]
		for _, l := range group[1:] {
			probs = append(probs, Problem{Kind: KindShadowed, Key: l.Key, Hostname: h,
				Detail: fmt.Sprintf("route %s not rendered: hostname %s is held by %s", l.Key, h, w.Key)})
		}
		if p, ok := checkRoute(w, h, defined, opts.ExternalMiddlewares); !ok {
			probs = append(probs, p)
			continue
		}
		name := Name(w.Key)
		lb := loadBalancer{
			Servers:        []server{{URL: w.Scheme + "://" + net.JoinHostPort(model.UnbracketHost(w.Host), strconv.Itoa(w.Port))}},
			PassHostHeader: true,
		}
		if w.Scheme == "https" && w.SkipVerify {
			lb.ServersTransport = InsecureTransport
			conf.ServersTransports[InsecureTransport] = transport{InsecureSkipVerify: true}
		}
		conf.Services[name] = service{LoadBalancer: lb}
		conf.Routers[name] = router{
			EntryPoints: []string{ep},
			Rule:        "Host(`" + h + "`)",
			Service:     name,
			Middlewares: append([]string(nil), w.Middlewares...),
		}
	}

	// Certificates.
	var entries []certEntry
	for _, c := range certs {
		if len(c.Domains) == 0 {
			continue
		}
		bad := ""
		for _, p := range []string{c.CertFile, c.KeyFile} {
			if err := cleanPath(p, false); err != nil && bad == "" {
				bad = err.Error()
			}
		}
		if bad != "" {
			probs = append(probs, Problem{Kind: KindInvalidCert, Detail: fmt.Sprintf("certificate for %s: %s", strings.Join(c.Domains, ","), bad)})
			continue
		}
		entries = append(entries, certEntry{CertFile: path.Join(prefix, c.CertFile), KeyFile: path.Join(prefix, c.KeyFile)})
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].CertFile != entries[j].CertFile {
			return entries[i].CertFile < entries[j].CertFile
		}
		return entries[i].KeyFile < entries[j].KeyFile
	})

	sort.Slice(probs, func(i, j int) bool {
		a, b := probs[i], probs[j]
		for _, c := range [][2]string{{a.Hostname, b.Hostname}, {a.Key, b.Key}, {a.Kind, b.Kind}, {a.Middleware, b.Middleware}, {a.Detail, b.Detail}} {
			if c[0] != c[1] {
				return c[0] < c[1]
			}
		}
		return false
	})

	rb, err := marshal(routesDoc{HTTP: conf})
	if err != nil {
		return nil, nil, err
	}
	tb, err := marshal(tlsDoc{TLS: tlsConf{Certificates: entries}})
	if err != nil {
		return nil, nil, err
	}
	return Files{RoutesFile: rb, TLSFile: tb}, probs, nil
}

// checkRoute re-validates a winner row: hostname, backend (the shared
// model.ValidateBackend predicate) and every middleware reference.
func checkRoute(r store.Route, h string, defined func(string) bool, external []string) (Problem, bool) {
	p := Problem{Key: r.Key, Hostname: h}
	if !validRouteHostname(h) {
		p.Kind, p.Detail = KindInvalidRoute, fmt.Sprintf("hostname %q is not a valid DNS name", r.Hostname)
		return p, false
	}
	if err := model.ValidateBackend(model.Backend{Scheme: r.Scheme, Host: r.Host, Port: r.Port}); err != nil {
		p.Kind, p.Detail = KindInvalidRoute, err.Error()
		return p, false
	}
	for _, ref := range r.Middlewares {
		if err := model.CheckMiddlewareRef(ref, defined, external); err != nil {
			p.Kind, p.Middleware = KindUndefinedMiddleware, ref
			if errors.Is(err, model.ErrInvalidMiddlewareRef) {
				p.Kind = KindInvalidMiddleware
			}
			p.Detail = "route not rendered (fail closed): " + err.Error()
			return p, false
		}
	}
	return p, true
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(Header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, fmt.Errorf("traefik: encode: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("traefik: encode: %w", err)
	}
	return buf.Bytes(), nil
}
