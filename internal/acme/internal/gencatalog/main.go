// Command gencatalog writes internal/acme/zz_gen_catalog.go and the
// dependency-free name list internal/acme/legonames/zz_gen_names.go from the
// provider descriptions (providers/dns/*/*.toml) shipped in the lego module
// that go.mod pins. It fails if a described provider is missing from lego's
// registry (providers/dns/zz_gen_dns_providers.go), so the catalog never
// offers a name lego cannot construct. Run it through
// `go generate ./internal/acme` after upgrading lego.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// excluded providers are never offered: "manual" needs an interactive
// terminal and "exec" runs an arbitrary program named in its settings.
var excluded = map[string]bool{"manual": true, "exec": true}

// envNameRe is a primary lego variable name. Lowercase aliases
// (TF_VAR_region) and prose that leaked into a description are dropped.
var envNameRe = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)

// registryCaseRe matches a `case "a", "b":` line of lego's registry.
var registryCaseRe = regexp.MustCompile(`^\s*case\s+("[^"]+"(?:\s*,\s*"[^"]+")*)\s*:`)

type provider struct {
	Code, Name, URL string
	Credentials     []string
	Additional      []string
}

func main() {
	out := flag.String("o", "zz_gen_catalog.go", "output file")
	namesOut := flag.String("names", "legonames/zz_gen_names.go", "output file of the name list")
	flag.Parse()
	dirB, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}|{{.Version}}", "github.com/go-acme/lego/v4").Output()
	if err != nil {
		log.Fatalf("locate lego module: %v", err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(dirB)), "|")
	files, err := filepath.Glob(filepath.Join(dir, "providers", "dns", "*", "*.toml"))
	if err != nil {
		log.Fatal(err)
	}
	registry, err := registryNames(filepath.Join(dir, "providers", "dns", "zz_gen_dns_providers.go"))
	if err != nil {
		log.Fatalf("read lego registry: %v", err)
	}
	var ps []provider
	for _, f := range files {
		p, err := parse(f)
		if err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		if p.Code == "" || excluded[p.Code] {
			continue
		}
		if !registry[p.Code] {
			log.Fatalf("%s: provider %q is not in lego's registry", f, p.Code)
		}
		p.Credentials, p.Additional = envNames(p.Credentials), envNames(p.Additional)
		ps = append(ps, p)
	}
	sort.Slice(ps, func(i, j int) bool { return ps[i].Code < ps[j].Code })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/acme/internal/gencatalog from lego %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package acme\n\n")
	fmt.Fprintf(&b, "// legoVersion is the lego release the catalog was generated from.\nconst legoVersion = %q\n\n", version)
	b.WriteString("var generatedCatalog = []ChallengeProvider{\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "{Name: %q, DisplayName: %q, URL: %q, Credentials: %s, Additional: %s},\n",
			p.Code, p.Name, p.URL, list(p.Credentials), list(p.Additional))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}

	b.Reset()
	fmt.Fprintf(&b, "// Code generated by internal/acme/internal/gencatalog from lego %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package legonames\n\n")
	b.WriteString("var names = []string{\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "%q,\n", p.Code)
	}
	b.WriteString("}\n")
	if src, err = format.Source(b.Bytes()); err != nil {
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*namesOut, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// envNames keeps the well-formed variable names (envNameRe).
func envNames(v []string) []string {
	var out []string
	for _, n := range v {
		if envNameRe.MatchString(n) {
			out = append(out, n)
		}
	}
	return out
}

// registryNames returns every name lego's NewDNSChallengeProviderByName
// accepts, read from its generated switch.
func registryNames(path string) (map[string]bool, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	for _, line := range strings.Split(string(src), "\n") {
		m := registryCaseRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		for _, q := range strings.Split(m[1], ",") {
			n, err := strconv.Unquote(strings.TrimSpace(q))
			if err != nil {
				return nil, err
			}
			out[n] = true
		}
	}
	if len(out) < 100 {
		return nil, fmt.Errorf("only %d names found; registry layout changed", len(out))
	}
	return out, nil
}

func list(v []string) string {
	if len(v) == 0 {
		return "nil"
	}
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// parse reads the few keys it needs from a lego provider description. The
// files are TOML with a fixed layout: top-level Name/URL/Code strings,
// multi-line literal strings, and KEY = "description" lines under
// [Configuration.Credentials] and [Configuration.Additional].
func parse(path string) (provider, error) {
	f, err := os.Open(path)
	if err != nil {
		return provider{}, err
	}
	defer f.Close()
	var p provider
	section, inMulti := "", false
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if inMulti {
			if strings.Contains(line, "'''") {
				inMulti = false
			}
			continue
		}
		if strings.Count(line, "'''") == 1 {
			inMulti = true
			continue
		}
		if strings.HasPrefix(line, "[") {
			section = strings.Trim(line, "[]")
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key, val = strings.TrimSpace(key), strings.TrimSpace(val)
		switch section {
		case "":
			s, err := strconv.Unquote(val)
			if err != nil {
				continue
			}
			switch key {
			case "Name":
				p.Name = s
			case "URL":
				p.URL = s
			case "Code":
				p.Code = s
			}
		case "Configuration.Credentials":
			p.Credentials = append(p.Credentials, key)
		case "Configuration.Additional":
			p.Additional = append(p.Additional, key)
		}
	}
	return p, sc.Err()
}
