// Command gencatalog writes internal/acme/zz_gen_catalog.go from the
// provider descriptions (providers/dns/*/*.toml) shipped in the lego module
// that go.mod pins. Run it through `go generate ./internal/acme` after
// upgrading lego.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// excluded providers are never offered: "manual" needs an interactive
// terminal and "exec" runs an arbitrary program named in its settings.
var excluded = map[string]bool{"manual": true, "exec": true}

type provider struct {
	Code, Name, URL string
	Credentials     []string
	Additional      []string
}

func main() {
	out := flag.String("o", "zz_gen_catalog.go", "output file")
	flag.Parse()
	dirB, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}|{{.Version}}", "github.com/go-acme/lego/v4").Output()
	if err != nil {
		log.Fatalf("locate lego module: %v", err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(dirB)), "|")
	files, err := filepath.Glob(filepath.Join(dir, "providers", "dns", "*", "*.toml"))
	if err != nil {
		log.Fatal(err)
	}
	var ps []provider
	for _, f := range files {
		p, err := parse(f)
		if err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		if p.Code == "" || excluded[p.Code] {
			continue
		}
		ps = append(ps, p)
	}
	sort.Slice(ps, func(i, j int) bool { return ps[i].Code < ps[j].Code })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/acme/internal/gencatalog from lego %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package acme\n\n")
	fmt.Fprintf(&b, "// legoVersion is the lego release the catalog was generated from.\nconst legoVersion = %q\n\n", version)
	b.WriteString("var generatedCatalog = []ChallengeProvider{\n")
	for _, p := range ps {
		fmt.Fprintf(&b, "{Name: %q, DisplayName: %q, URL: %q, Credentials: %s, Additional: %s},\n",
			p.Code, p.Name, p.URL, list(p.Credentials), list(p.Additional))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func list(v []string) string {
	if len(v) == 0 {
		return "nil"
	}
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// parse reads the few keys it needs from a lego provider description. The
// files are TOML with a fixed layout: top-level Name/URL/Code strings,
// multi-line literal strings, and KEY = "description" lines under
// [Configuration.Credentials] and [Configuration.Additional].
func parse(path string) (provider, error) {
	f, err := os.Open(path)
	if err != nil {
		return provider{}, err
	}
	defer f.Close()
	var p provider
	section, inMulti := "", false
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if inMulti {
			if strings.Contains(line, "'''") {
				inMulti = false
			}
			continue
		}
		if strings.Count(line, "'''") == 1 {
			inMulti = true
			continue
		}
		if strings.HasPrefix(line, "[") {
			section = strings.Trim(line, "[]")
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key, val = strings.TrimSpace(key), strings.TrimSpace(val)
		switch section {
		case "":
			s, err := strconv.Unquote(val)
			if err != nil {
				continue
			}
			switch key {
			case "Name":
				p.Name = s
			case "URL":
				p.URL = s
			case "Code":
				p.Code = s
			}
		case "Configuration.Credentials":
			p.Credentials = append(p.Credentials, key)
		case "Configuration.Additional":
			p.Additional = append(p.Additional, key)
		}
	}
	return p, sc.Err()
}
